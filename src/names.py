def _strip_accents(text: str) -> str:
    decomposed = unicodedata.normalize("NFKD", text)
    return "".join(ch for ch in decomposed if not unicodedata.combining(ch))


def _basic(name: str) -> str:
    text = (
        name.replace("ø", "o")
        .replace("Ø", "O")
        .replace("æ", "ae")
        .replace("Æ", "AE")
        .replace("ð", "d")
        .replace("Ð", "D")
        .replace("þ", "th")
        .replace("Þ", "Th")
        .replace("ł", "l")
        .replace("Ł", "L")
        .replace("đ", "d")
        .replace("Đ", "D")
    )
    text = _strip_accents(text)
    text = text.replace("İ", "I").replace("ı", "i").replace("ß", "ss")
    text = re.sub(r"\[[^\]]*\]", " ", text)
    text = re.sub(r"\([^)]*\)", " ", text)
    text = text.replace("&", " and ")
    text = text.replace("'", "")
    text = text.lower()
    text = re.sub(r"[^a-z0-9]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


# Square-bracket notes on a club line are source status, not part of the name.
_VOID_TAG = re.compile(
    r"\[(cancelled|canceled|abandoned|postponed|void|suspended)\]",
    re.IGNORECASE,
)


def clean_display_name(name: str | None) -> str:
    """Drop country codes and source notes such as ``[cancelled]`` from a label."""
    if not name:
        return ""
    text = re.sub(r"\s*\([A-Z]{3}\)\s*", " ", str(name))
    text = re.sub(r"\s*\[[^\]]*\]", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def has_void_tag(name: str | None) -> bool:
    """True when a source marked the match cancelled, abandoned, or postponed."""
    return bool(name and _VOID_TAG.search(str(name)))


def canonicalize(name: str | None) -> str | None:
    """Return a stable club key, or None if the name is empty."""
    if not name or not str(name).strip():
        return None
    basic = _basic(name)
    if not basic:
        return None
    if basic in _ALIASES:
        return _ALIASES[basic]
    tokens = [tok for tok in basic.split() if tok not in _STOP]
    # Keep a leading number that is part of a club (Bayer 04) but drop a
    # lone trailing "04" style only when the alias table already handled it.
    key = " ".join(tokens).strip()
    if not key:
        key = basic
    return _ALIASES.get(key, key)


def slugify(canonical: str) -> str:
    return canonical.replace(" ", "-")


def pretty_fallback(canonical: str) -> str:
    return " ".join(part.capitalize() for part in canonical.split())
